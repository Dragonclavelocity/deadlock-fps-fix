"""Generates assets/banner.svg (animated, CSS keyframes, no scripts, no external fonts; the photo is embedded
as a data URI) and design/marketing/banner.html (same SVG inlined + Instrument Serif/Sans webfonts, used to
render assets/banner.png).  Run from the repo root:  python design/marketing/gen_banner.py

The background is a 1280x400 crop of the official Steam screenshot in design/img/deadlock-bg.jpg
(see DESIGN.md "Image sources": Valve promotional material, replace before publishing)."""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
BG_JPG = HERE / "banner-bg.jpg"   # made from design/img/deadlock-bg.jpg (crop 1920x600 at y 200, q72)

SERIF = "'Instrument Serif',Georgia,'Times New Roman',serif"
SANS = "'Instrument Sans',Inter,'Segoe UI',-apple-system,BlinkMacSystemFont,'Helvetica Neue',Arial,sans-serif"
TEXT, TEXT2, TEXT3, ACC, INK = "#f1ece2", "#b9b3a8", "#7d776d", "#ebe2cf", "#15130f"

img64 = base64.b64encode(BG_JPG.read_bytes()).decode()

cx, cy, cw, ch = 868, 62, 348, 276
rows = [("Competitive", "168", "+74", 150), ("Balanced", "141", "+47", 218), ("Quality", "112", "+18", 286)]
row_svg = []
for name, fps, gain, y in rows:
    row_svg.append(
        f'<text x="{cx+28}" y="{y+6}" font-family="{SANS}" font-size="16" font-weight="600" fill="{TEXT}">{name}</text>'
        f'<text x="{cx+cw-74}" y="{y+12}" text-anchor="end" font-family="{SERIF}" font-size="40" fill="{TEXT}">{fps}</text>'
        f'<text x="{cx+cw-28}" y="{y+11}" text-anchor="end" font-family="{SANS}" font-size="13" fill="{TEXT2}">{gain}</text>')
ROWS = "\n  ".join(row_svg)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="1280" height="400" viewBox="0 0 1280 400" role="img" aria-labelledby="t d">
  <title id="t">Deadlock FPS Fix — free FPS boost, custom FOV and stretched resolution for Deadlock</title>
  <desc id="d">Deadlock FPS Fix: FPS presets Competitive 168, Balanced 141 and Quality 112 estimated fps on an RX 6700 XT, plus field of view and stretched resolution.</desc>
  <style>
    .kb{{transform-origin:640px 200px;animation:kb 12s ease-in-out infinite}}
    @keyframes kb{{0%,100%{{transform:scale(1)}}50%{{transform:scale(1.06)}}}}
    .hl{{animation:hl 12s ease-in-out infinite}}
    @keyframes hl{{0%,28%{{transform:translateY(0)}}34%,61%{{transform:translateY(-68px)}}67%,94%{{transform:translateY(68px)}}100%{{transform:translateY(0)}}}}
  </style>
  <rect width="1280" height="400" fill="#0a0a0c"/>
  <image class="kb" width="1280" height="400" preserveAspectRatio="xMidYMid slice" href="data:image/jpeg;base64,{img64}" xlink:href="data:image/jpeg;base64,{img64}"/>
  <rect width="1280" height="400" fill="#08090c" fill-opacity=".55"/>

  <circle cx="75" cy="78" r="10" fill="none" stroke="{ACC}" stroke-width="2"/>
  <rect x="71" y="77" width="8" height="2" fill="{ACC}"/>
  <text x="96" y="84" font-family="{SANS}" font-size="17" font-weight="600" fill="{TEXT}">Deadlock FPS Fix</text>

  <text x="62" y="196" font-family="{SERIF}" font-size="80" fill="{TEXT}" letter-spacing="-.5">Smooth frames,</text>
  <text x="64" y="276" font-family="{SERIF}" font-size="80" font-style="italic" fill="{ACC}" letter-spacing="-.5">a wider view.</text>
  <text x="66" y="332" font-family="{SANS}" font-size="18" fill="{TEXT2}">Free FPS presets, custom FOV and stretched resolution for Deadlock</text>

  <rect x="{cx+.5}" y="{cy+.5}" width="{cw}" height="{ch}" rx="18" fill="#0c0c0e" fill-opacity=".8" stroke="#ffffff" stroke-opacity=".1"/>
  <text x="{cx+28}" y="{cy+40}" font-family="{SANS}" font-size="13" fill="{TEXT3}">Estimated fps · RX 6700 XT · 1440p</text>
  <rect class="hl" x="{cx+14}" y="{218-30}" width="{cw-28}" height="56" rx="12" fill="none" stroke="{ACC}" stroke-width="1.5"/>
  {ROWS}
</svg>
'''
(ROOT / "assets/banner.svg").write_text(svg, encoding="utf-8")

html = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Deadlock FPS Fix — banner (PNG source, generated by gen_banner.py)</title>
<link href="https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Instrument+Sans:wght@400;500;600&display=swap" rel="stylesheet">
<style>html,body{{margin:0;width:1280px;height:400px;overflow:hidden;background:#0a0a0c}}svg{{display:block}}</style>
</head>
<body>
{svg}
</body>
</html>
'''
(HERE / "banner.html").write_text(html, encoding="utf-8")
print("wrote assets/banner.svg (%d KB) and design/marketing/banner.html" % (len(svg) // 1024))
